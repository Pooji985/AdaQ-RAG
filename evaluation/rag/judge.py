"""Provider-independent answer-quality judge interface and implementations.

Implements LLM-as-a-judge evaluation scoring generated answers across:
- Correctness (0-4): Factual fidelity against gold reference answer
- Faithfulness (0-4): Grounding in retrieved evidence (absence of hallucinations)
- Relevance (0-4): Directness in answering the user question
- Overall: Arithmetic mean of the three dimensions

CRITICAL: The system name (e.g., 'AdaQ-RAG', 'Baseline RAG') MUST NOT be provided
to the judge to prevent evaluation bias.
"""

from abc import ABC, abstractmethod
import json
import logging
import re
from typing import Any, Callable, Sequence

from adaq_rag.llm.base import BaseLLMProvider
from adaq_rag.llm.factory import get_llm_provider
from evaluation.rag.models import AnswerQualityScores

logger = logging.getLogger("adaq_rag.evaluation.judge")

JUDGE_SYSTEM_PROMPT = """You are an impartial, expert technical evaluator assessing the quality of answers generated by an AI assistant on scikit-learn machine learning documentation.

You must evaluate the candidate answer objectively based ONLY on the provided Question, Reference Answer, and Retrieved Evidence.

SCORING CRITERIA (0.0 to 4.0 scale):
1. Correctness (0.0 - 4.0):
   - Compare Candidate Answer with the Gold Reference Answer.
   - Does the Candidate Answer contain accurate facts, parameters, and algorithms matching the reference answer?
   - Score interpretation:
     * 0: completely inaccurate or contradicts reference answer
     * 0 to <1: very poor, major factual errors
     * 1 to <2: partially satisfies, some accurate points but significant omissions/flaws
     * 2 to <3: mostly satisfactory, mostly accurate with minor gaps
     * 3 to 4: strongly satisfies, entirely accurate and comprehensive

2. Faithfulness (0.0 - 4.0):
   - Compare Candidate Answer with the Retrieved Evidence.
   - Are all factual claims, parameters, and code snippets in the Candidate Answer grounded in and supported by the Retrieved Evidence?
   - Any hallucination or unsupported claim lowers faithfulness.
   - Score interpretation:
     * 0: completely ungrounded or hallucinated
     * 0 to <1: very poor, majority of claims unsupported by evidence
     * 1 to <2: partially satisfies, mixture of grounded facts and unsupported assertions
     * 2 to <3: mostly satisfactory, largely grounded with slight unverified details
     * 3 to 4: strongly satisfies, strictly faithful and fully verified by evidence

3. Relevance (0.0 - 4.0):
   - Compare Candidate Answer with the User Question.
   - Does the Candidate Answer directly and concisely answer the question asked without extraneous evasion or filler?
   - Score interpretation:
     * 0: completely irrelevant / does not address question
     * 0 to <1: very poor, mostly evasive or off-topic
     * 1 to <2: partially satisfies, addresses topic tangentially
     * 2 to <3: mostly satisfactory, directly answers main question
     * 3 to 4: strongly satisfies, directly, clearly, and precisely answers the question

OUTPUT FORMAT:
Respond with a single valid JSON object strictly matching this schema:
{
  "correctness": <float between 0.0 and 4.0>,
  "faithfulness": <float between 0.0 and 4.0>,
  "relevance": <float between 0.0 and 4.0>,
  "reason": "<concise 1-2 sentence justification for the scores>"
}
"""

JUDGE_USER_PROMPT_TEMPLATE = """Evaluate the following candidate answer according to the specified rubric.

[QUESTION]
{question}

[GOLD REFERENCE ANSWER]
{reference_answer}

[RETRIEVED EVIDENCE]
{retrieved_evidence}

[CANDIDATE ANSWER TO EVALUATE]
{generated_answer}

Respond ONLY with the JSON object:"""


def format_evidence(evidence: str | Sequence[str]) -> str:
    """Format retrieved evidence snippets into a clean, numbered context string.

    Args:
        evidence: String or sequence of text snippets.

    Returns:
        Formatted evidence string.
    """
    if isinstance(evidence, str):
        return evidence.strip() or "No evidence provided."

    if not evidence:
        return "No evidence provided."

    formatted_snippets = []
    for idx, snippet in enumerate(evidence, start=1):
        clean_snip = snippet.strip() if isinstance(snippet, str) else str(snippet).strip()
        formatted_snippets.append(f"[Evidence Snippet {idx}]\n{clean_snip}")

    return "\n\n".join(formatted_snippets)


class BaseJudge(ABC):
    """Abstract interface for answer-quality evaluation judges."""

    @abstractmethod
    def evaluate(
        self,
        question: str,
        reference_answer: str,
        retrieved_evidence: str | Sequence[str],
        generated_answer: str,
    ) -> AnswerQualityScores:
        """Evaluate candidate answer quality synchronously.

        NOTE: The system name MUST NOT be passed to this function.

        Args:
            question: Original user query.
            reference_answer: Gold reference answer.
            retrieved_evidence: Retrieved evidence context or list of snippet strings.
            generated_answer: Candidate system answer to evaluate.

        Returns:
            AnswerQualityScores: Graded scores (0-4) with short reason.
        """

    @abstractmethod
    async def evaluate_async(
        self,
        question: str,
        reference_answer: str,
        retrieved_evidence: str | Sequence[str],
        generated_answer: str,
    ) -> AnswerQualityScores:
        """Evaluate candidate answer quality asynchronously.

        NOTE: The system name MUST NOT be passed to this function.
        """


class LLMJudge(BaseJudge):
    """LLM-as-a-judge answer quality evaluator using configured LLM provider."""

    def __init__(self, provider: BaseLLMProvider | None = None) -> None:
        """Initialize LLM judge.

        Args:
            provider: Optional LLM provider instance. If None, resolves from factory.
        """
        self.provider = provider or get_llm_provider()

    def _build_prompt(
        self,
        question: str,
        reference_answer: str,
        retrieved_evidence: str | Sequence[str],
        generated_answer: str,
    ) -> str:
        formatted_ev = format_evidence(retrieved_evidence)
        return JUDGE_USER_PROMPT_TEMPLATE.format(
            question=question.strip(),
            reference_answer=reference_answer.strip(),
            retrieved_evidence=formatted_ev,
            generated_answer=generated_answer.strip(),
        )

    def _parse_response(self, text: str) -> AnswerQualityScores:
        """Parse and clamp JSON judge response."""
        cleaned = text.strip()

        # Handle Markdown json code blocks
        json_match = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", cleaned, re.DOTALL)
        if json_match:
            json_str = json_match.group(1)
        else:
            # Fallback to searching first { and last }
            brace_match = re.search(r"(\{.*\})", cleaned, re.DOTALL)
            json_str = brace_match.group(1) if brace_match else cleaned

        try:
            data = json.loads(json_str)
            raw_c = float(data.get("correctness", 0.0))
            raw_f = float(data.get("faithfulness", 0.0))
            raw_r = float(data.get("relevance", 0.0))
            reason = str(data.get("reason", "")).strip()

            # Clamp scores strictly into [0.0, 4.0]
            c = max(0.0, min(4.0, raw_c))
            f = max(0.0, min(4.0, raw_f))
            r = max(0.0, min(4.0, raw_r))
            overall = round((c + f + r) / 3.0, 4)

            return AnswerQualityScores(
                correctness=c,
                faithfulness=f,
                relevance=r,
                overall=overall,
                reason=reason or "Evaluated by LLM Judge.",
            )
        except Exception as err:
            logger.warning("Failed to parse LLM judge response: %s (raw text: %r)", err, text)
            # Conservative fallback score
            return AnswerQualityScores(
                correctness=0.0,
                faithfulness=0.0,
                relevance=0.0,
                overall=0.0,
                reason=f"Failed to parse judge output: {err}",
            )

    def evaluate(
        self,
        question: str,
        reference_answer: str,
        retrieved_evidence: str | Sequence[str],
        generated_answer: str,
    ) -> AnswerQualityScores:
        prompt = self._build_prompt(
            question, reference_answer, retrieved_evidence, generated_answer
        )
        response = self.provider.generate(prompt=prompt, system_prompt=JUDGE_SYSTEM_PROMPT)
        return self._parse_response(response.content)

    async def evaluate_async(
        self,
        question: str,
        reference_answer: str,
        retrieved_evidence: str | Sequence[str],
        generated_answer: str,
    ) -> AnswerQualityScores:
        prompt = self._build_prompt(
            question, reference_answer, retrieved_evidence, generated_answer
        )
        response = await self.provider.generate_async(
            prompt=prompt, system_prompt=JUDGE_SYSTEM_PROMPT
        )
        return self._parse_response(response.content)


class MockJudge(BaseJudge):
    """Deterministic mock judge for local testing and offline evaluation without API calls.

    Allows configuring fixed default scores or a custom scoring function.
    Tracks all evaluation call parameters for verification.
    """

    def __init__(
        self,
        default_scores: AnswerQualityScores | None = None,
        scoring_fn: (
            Callable[[str, str, str | Sequence[str], str], AnswerQualityScores] | None
        ) = None,
    ) -> None:
        """Initialize MockJudge.

        Args:
            default_scores: Fixed scores to return on evaluate calls.
            scoring_fn: Callable receiving (question, reference_answer, evidence, answer)
                and returning AnswerQualityScores.
        """
        self.default_scores = default_scores
        self.scoring_fn = scoring_fn
        self.call_history: list[dict[str, Any]] = []

    def _evaluate_impl(
        self,
        question: str,
        reference_answer: str,
        retrieved_evidence: str | Sequence[str],
        generated_answer: str,
    ) -> AnswerQualityScores:
        self.call_history.append(
            {
                "question": question,
                "reference_answer": reference_answer,
                "retrieved_evidence": retrieved_evidence,
                "generated_answer": generated_answer,
            }
        )

        if self.scoring_fn is not None:
            return self.scoring_fn(
                question, reference_answer, retrieved_evidence, generated_answer
            )

        if self.default_scores is not None:
            return self.default_scores.model_copy()

        # Sensible deterministic mock score
        if not generated_answer.strip():
            return AnswerQualityScores(
                correctness=0.0,
                faithfulness=0.0,
                relevance=0.0,
                overall=0.0,
                reason="Empty generated answer provided.",
            )

        return AnswerQualityScores(
            correctness=3.5,
            faithfulness=3.5,
            relevance=3.5,
            overall=3.5,
            reason="MockJudge: default satisfactory evaluation.",
        )

    def evaluate(
        self,
        question: str,
        reference_answer: str,
        retrieved_evidence: str | Sequence[str],
        generated_answer: str,
    ) -> AnswerQualityScores:
        return self._evaluate_impl(
            question, reference_answer, retrieved_evidence, generated_answer
        )

    async def evaluate_async(
        self,
        question: str,
        reference_answer: str,
        retrieved_evidence: str | Sequence[str],
        generated_answer: str,
    ) -> AnswerQualityScores:
        return self._evaluate_impl(
            question, reference_answer, retrieved_evidence, generated_answer
        )
